#!/usr/bin/env bash
# Build R2 Agent and/or R2 Main without Gradle, on Linux or macOS. Same output as apps/build.ps1.
# Usage: apps/build.sh [agent|main|all] [--release]
#   --release: no API token built in; each robot then uses only its own (tools\r2.ps1 fetch-token).
# Tools: JDK from $JAVA_HOME (or tools/jdk), Android SDK from $ANDROID_HOME / $ANDROID_SDK_ROOT
# (or tools/android-sdk) with "build-tools;35.0.1" and "platforms;android-19".
# Output: apps/out/R2Agent.apk, apps/out/R2Main.apk
set -euo pipefail

APP=all
RELEASE=0
for arg in "$@"; do
    case "$arg" in
        agent|main|all) APP=$arg ;;
        --release|-Release) RELEASE=1 ;;
        *) echo "usage: $0 [agent|main|all] [--release]" >&2; exit 2 ;;
    esac
done

APPS_DIR=$(cd "$(dirname "$0")" && pwd)
ROOT=$(dirname "$APPS_DIR")
TOOLS=$ROOT/tools
SECRETS=$ROOT/secrets
OUT_DIR=$APPS_DIR/out

if [ -x "$TOOLS/jdk/bin/javac" ]; then JDK=$TOOLS/jdk; else JDK=${JAVA_HOME:-}; fi
if [ -z "$JDK" ] || [ ! -x "$JDK/bin/javac" ]; then echo "JDK not found: set JAVA_HOME or unpack one to tools/jdk" >&2; exit 1; fi
if [ -d "$TOOLS/android-sdk" ]; then SDK=$TOOLS/android-sdk; else SDK=${ANDROID_HOME:-${ANDROID_SDK_ROOT:-}}; fi
BT=$SDK/build-tools/35.0.1
ANDROID_JAR=$SDK/platforms/android-19/android.jar
for f in "$BT/d8" "$BT/aapt2" "$BT/zipalign" "$BT/apksigner" "$ANDROID_JAR"; do
    if [ ! -e "$f" ]; then
        echo "missing $f" >&2
        echo "install with: sdkmanager \"build-tools;35.0.1\" \"platforms;android-19\"" >&2
        exit 1
    fi
done
export JAVA_HOME=$JDK
export PATH=$JDK/bin:$PATH
mkdir -p "$SECRETS" "$OUT_DIR"

# One signing key for both apps, plus a development API token baked into the agent (not with --release).
KEYSTORE=$SECRETS/r2hack.keystore
PASS_FILE=$SECRETS/keystore-pass.txt
TOKEN_FILE=$SECRETS/agent-token.txt
random_hex() { od -An -N"$1" -tx1 /dev/urandom | tr -d ' \n'; }
[ -f "$PASS_FILE" ] || { random_hex 16 > "$PASS_FILE"; chmod 600 "$PASS_FILE"; }
[ -f "$TOKEN_FILE" ] || { random_hex 24 > "$TOKEN_FILE"; chmod 600 "$TOKEN_FILE"; }
PASS=$(tr -d ' \r\n' < "$PASS_FILE")
if [ "$RELEASE" = 1 ]; then TOKEN=""; else TOKEN=$(tr -d ' \r\n' < "$TOKEN_FILE"); fi
if [ ! -f "$KEYSTORE" ]; then
    keytool -genkeypair -keystore "$KEYSTORE" -storepass "$PASS" -keypass "$PASS" \
        -alias r2hack -keyalg RSA -keysize 2048 -validity 10000 -dname CN=r2hack
fi

# versionCode = minutes since 2025-01-01, so every build can replace the previous one.
VERSION_CODE=$(( ($(date -u +%s) - $(date -u -d 2025-01-01 +%s 2>/dev/null || date -u -j -f %Y-%m-%d 2025-01-01 +%s)) / 60 ))
VERSION_NAME=$(date +%Y.%m.%d-%H%M)

# build_app <name> <dir> <apk name> <generate function>
build_app() {
    local name=$1 dir=$2 apk=$3 generate=$4
    echo "== $name $VERSION_NAME ($VERSION_CODE)"
    local work=$OUT_DIR/build-$name
    rm -rf "$work"
    mkdir -p "$work/gen" "$work/classes" "$work/dex"
    "$generate" "$work/gen"

    find "$dir/src" "$work/gen" -name '*.java' > "$work/sources.txt"
    javac -source 8 -target 8 -nowarn -Xlint:-options -encoding UTF-8 \
        -bootclasspath "$ANDROID_JAR" -classpath "$ANDROID_JAR" -d "$work/classes" @"$work/sources.txt"

    jar cf "$work/classes.jar" -C "$work/classes" .
    "$BT/d8" --release --min-api 19 --lib "$ANDROID_JAR" --output "$work/dex" "$work/classes.jar"

    local link=(link -o "$work/unsigned.apk" -I "$ANDROID_JAR" --manifest "$dir/AndroidManifest.xml"
        --min-sdk-version 19 --target-sdk-version 19
        --version-code "$VERSION_CODE" --version-name "$VERSION_NAME")
    local assets=$work/assets
    if [ -d "$dir/assets" ]; then cp -R "$dir/assets" "$assets"; fi
    if [ -d "$dir/web" ]; then
        # The agent's web control page, copied flat as web-<name> (same layout as build.ps1).
        mkdir -p "$assets"
        for f in "$dir/web"/*; do [ -f "$f" ] && cp "$f" "$assets/web-$(basename "$f")"; done
    fi
    if [ -d "$assets" ]; then link+=(-A "$assets"); fi
    "$BT/aapt2" "${link[@]}"

    (cd "$work/dex" && zip -q -j "$work/unsigned.apk" classes.dex)

    "$BT/zipalign" -f -p 4 "$work/unsigned.apk" "$work/aligned.apk"
    "$BT/apksigner" sign --ks "$KEYSTORE" --ks-pass "pass:$PASS" --ks-key-alias r2hack \
        --min-sdk-version 19 --out "$OUT_DIR/$apk" "$work/aligned.apk"
    echo "   -> $OUT_DIR/$apk"
}

gen_agent() {
    local d=$1/dev/r2hack/agent
    mkdir -p "$d"
    cat > "$d/Secrets.java" <<EOF
package dev.r2hack.agent;
// Generated by apps/build.sh -- do not edit or commit.
final class Secrets {
    static final String TOKEN = "$TOKEN";
    static final String VERSION = "$VERSION_NAME";
    private Secrets() {}
}
EOF
}

gen_main() {
    local d=$1/dev/r2hack/main
    mkdir -p "$d"
    cat > "$d/BuildInfo.java" <<EOF
package dev.r2hack.main;
// Generated by apps/build.sh.
final class BuildInfo {
    static final String VERSION = "$VERSION_NAME";
    private BuildInfo() {}
}
EOF
}

# The UART library (libr2d2.so) is not bundled: the agent loads the robot's own copy at runtime.
if [ "$APP" = agent ] || [ "$APP" = all ]; then build_app agent "$APPS_DIR/agent" R2Agent.apk gen_agent; fi
if [ "$APP" = main ] || [ "$APP" = all ]; then build_app main "$APPS_DIR/main" R2Main.apk gen_main; fi
